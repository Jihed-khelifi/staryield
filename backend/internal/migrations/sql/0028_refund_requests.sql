-- 0028_refund_requests: in-app refund requests and the indexes of the revenue
-- report (revisions 5.0, docs/platform-extensions.md §24.4 and §24.5).
--
-- * refund_requests is the state machine of a client's request to get money
--   back for one credit-pack payment (open -> approved | denied | credited |
--   withdrawn; terminal states never move). The quote the client saw is stored
--   as columns (not a JSON blob): every figure is a bigint the admin list and
--   the revenue report can filter and aggregate on. At most one request per
--   payment is open (partial unique index) and a client's retry of the same
--   submission is recognised by (user_id, idempotency_key).
-- * The other statements are the indexes the revenue report needs so that it
--   never scans a whole table: purchases paid in a period, successful refunds
--   in a period, disputed payments in a period, the open purchase lots whose
--   remaining value is the deferred revenue, and the append-only lot
--   allocations by time.

-- ---------------------------------------------------------------------------
-- refund_requests
-- ---------------------------------------------------------------------------
CREATE TABLE refund_requests (
    id                    uuid        PRIMARY KEY,
    -- "RR-" + 8 Crockford base32 characters, generated by the server.
    reference             text        NOT NULL,
    user_id               uuid        NOT NULL REFERENCES users (id),
    transaction_id        uuid        NOT NULL REFERENCES payment_transactions (id),
    credit_purchase_id    uuid        NOT NULL REFERENCES credit_purchases (id),
    pack_id               uuid        NOT NULL REFERENCES credit_packs (id),
    status                text        NOT NULL DEFAULT 'open',
    reason                text        NOT NULL,
    details               text        NOT NULL DEFAULT '',
    channel               text        NOT NULL,
    idempotency_key       text        NOT NULL,

    -- The quote when the request was made (RefundQuote of §24.4).
    quote_pack_name       text        NOT NULL,
    quote_currency        text        NOT NULL,
    quote_amount_paid_cents       bigint      NOT NULL,
    quote_already_refunded_cents  bigint      NOT NULL,
    quote_credits_purchased       bigint      NOT NULL,
    quote_credits_used            bigint      NOT NULL,
    quote_credits_remaining       bigint      NOT NULL,
    quote_refundable_cents        bigint      NOT NULL,
    quote_purchased_at            timestamptz NOT NULL,
    quote_window_ends_at          timestamptz NOT NULL,
    quote_within_window           boolean     NOT NULL,

    -- The resolution.
    resolution_note       text        NOT NULL DEFAULT '',
    refunded_cents        bigint,
    credits_granted       bigint,
    refund_transaction_id uuid        REFERENCES payment_transactions (id),
    resolved_by           uuid        REFERENCES users (id),
    resolved_at           timestamptz,

    created_at            timestamptz NOT NULL DEFAULT now(),
    updated_at            timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT refund_requests_reference_valid CHECK (reference ~ '^RR-[0-9A-HJKMNP-TV-Z]{8}$'),
    CONSTRAINT refund_requests_status_valid CHECK (status IN ('open', 'approved', 'denied', 'credited', 'withdrawn')),
    CONSTRAINT refund_requests_reason_valid CHECK (reason IN (
        'unused_credits', 'technical_problem', 'incorrect_charge', 'unauthorized_charge', 'reading_concern', 'other')),
    CONSTRAINT refund_requests_channel_valid CHECK (channel IN ('web', 'email', 'admin')),
    CONSTRAINT refund_requests_details_length CHECK (char_length(details) <= 2000),
    CONSTRAINT refund_requests_note_length CHECK (char_length(resolution_note) <= 1000),
    CONSTRAINT refund_requests_key_length CHECK (char_length(idempotency_key) BETWEEN 1 AND 128),
    CONSTRAINT refund_requests_quote_valid CHECK (
        quote_amount_paid_cents > 0 AND quote_already_refunded_cents >= 0 AND quote_credits_purchased >= 0
        AND quote_credits_used >= 0 AND quote_credits_remaining >= 0 AND quote_refundable_cents >= 0
        AND quote_window_ends_at >= quote_purchased_at),
    -- Open is the only state without a resolution; the other states record
    -- what was decided and nothing else.
    CONSTRAINT refund_requests_resolution_valid CHECK (
        (status = 'open') = (resolved_at IS NULL)
        AND (status = 'approved') = (refunded_cents IS NOT NULL AND refund_transaction_id IS NOT NULL)
        AND (status = 'credited') = (credits_granted IS NOT NULL)
        AND (refunded_cents IS NULL OR refunded_cents > 0)
        AND (credits_granted IS NULL OR credits_granted > 0))
);

CREATE UNIQUE INDEX refund_requests_reference_key ON refund_requests (reference);
-- One open request per payment: concurrent submissions cannot both win.
CREATE UNIQUE INDEX refund_requests_open_transaction_key ON refund_requests (transaction_id) WHERE status = 'open';
-- A client's retry of the same submission.
CREATE UNIQUE INDEX refund_requests_idempotency_key ON refund_requests (user_id, idempotency_key);
-- Admin list (status filter), the unfiltered admin list, and the per-user lists
-- (client history, admin user filter): all keyset-paged on (created_at, id).
CREATE INDEX refund_requests_status_created_idx ON refund_requests (status, created_at DESC, id DESC);
CREATE INDEX refund_requests_created_idx ON refund_requests (created_at DESC, id DESC);
CREATE INDEX refund_requests_user_created_idx ON refund_requests (user_id, created_at DESC, id DESC);
-- The newest request of each payment on a transactions page (one batched query).
CREATE INDEX refund_requests_transaction_idx ON refund_requests (transaction_id, created_at DESC);
CREATE INDEX refund_requests_refund_transaction_idx ON refund_requests (refund_transaction_id) WHERE refund_transaction_id IS NOT NULL;

CREATE TRIGGER refund_requests_touch_updated_at BEFORE UPDATE ON refund_requests
    FOR EACH ROW EXECUTE FUNCTION touch_updated_at();

COMMENT ON TABLE refund_requests IS
    'Client refund requests for credit-pack payments (state machine: open -> approved | denied | credited | withdrawn). The quote columns are the snapshot the client saw.';

-- ---------------------------------------------------------------------------
-- Revenue report indexes (§24.5)
-- ---------------------------------------------------------------------------
-- Purchases paid in a period, refunded ones included (a refund is reported
-- next to the purchase it undoes; index-only for the totals).
CREATE INDEX credit_purchases_paid_completed_idx
    ON credit_purchases (completed_at) INCLUDE (pack_id, user_id, price_cents, credits, currency)
    WHERE status IN ('succeeded', 'refunded');
-- Successful refunds of credit purchases in a period.
CREATE INDEX payment_transactions_refund_created_idx
    ON payment_transactions (created_at) INCLUDE (amount_cents, currency)
    WHERE kind = 'refund' AND status = 'succeeded' AND credit_purchase_id IS NOT NULL;
-- Credit-purchase payments flagged as disputed, by when the flag was set.
CREATE INDEX payment_transactions_disputed_idx
    ON payment_transactions (updated_at) WHERE status = 'disputed' AND kind = 'credit_purchase';
-- Deferred revenue: what is still unconsumed in purchase lots.
CREATE INDEX credit_lots_purchase_value_idx
    ON credit_lots (created_at) INCLUDE (value_remaining_millicents)
    WHERE source = 'purchase' AND value_remaining_millicents > 0;
-- Deferred revenue at a past instant: what was consumed or clawed back since
-- then. Allocations are append-only and arrive in time order, so a plain
-- b-tree on their time grows only at its right edge (cheap) and serves any
-- "since" window with an index range scan.
CREATE INDEX credit_lot_allocations_created_idx ON credit_lot_allocations (created_at);
-- Advisor earnings in a period (advisor cost): index-only on the period.
CREATE INDEX psychic_earnings_created_idx ON psychic_earnings (created_at) INCLUDE (net_credits);
-- Welcome-offer redemptions completed in a period.
CREATE INDEX offer_redemptions_redeemed_idx ON offer_redemptions (redeemed_at) WHERE status = 'redeemed';
