type numerologyVector struct {
	BirthDate      string `json:"birth_date"`
	AsOf           string `json:"as_of"`
	LifePath       int    `json:"life_path"`
	LifePathMaster bool   `json:"life_path_master"`
	PersonalYear   int    `json:"personal_year"`
	PersonalMonth  int    `json:"personal_month"`
	PersonalDay    int    `json:"personal_day"`
	Instant        string `json:"instant"`
	TZ             string `json:"tz"`
}

// TestNumerologyFixtures checks the shared vectors (also used by the
// frontend), generated by an independent implementation of the formulas.
func TestNumerologyFixtures(t *testing.T) {
	raw, err := os.ReadFile("testdata/numerology_vectors.json")
	if err != nil {
		t.Fatal(err)
	}
	var f struct {
		Vectors         []numerologyVector `json:"vectors"`
		TimezoneVectors []numerologyVector `json:"timezone_vectors"`
	}
	if err := json.Unmarshal(raw, &f); err != nil {
		t.Fatal(err)
	}
	if n := len(f.Vectors) + len(f.TimezoneVectors); n < 40 {
		t.Fatalf("only %d vectors", n)
	}
	check := func(v numerologyVector, asOf time.Time) {
		t.Helper()
		b, err := time.Parse(time.DateOnly, v.BirthDate)
		if err != nil {
			t.Fatal(err)
		}
		lp := LifePathReduction(b.Year(), int(b.Month()), b.Day())
		if lp.Number != v.LifePath || lp.Master != v.LifePathMaster {
			t.Errorf("%s: life path %d (master %v), want %d (%v)", v.BirthDate, lp.Number, lp.Master, v.LifePath, v.LifePathMaster)
		}
		py := PersonalYear(int(b.Month()), b.Day(), asOf)
		pm := PersonalMonth(int(b.Month()), b.Day(), asOf)
		pd := PersonalDay(int(b.Month()), b.Day(), asOf)
		if py != v.PersonalYear || pm != v.PersonalMonth || pd != v.PersonalDay {
			t.Errorf("%s as of %s: PY %d PM %d PD %d, want %d %d %d", v.BirthDate, asOf.Format(time.DateOnly), py, pm, pd, v.PersonalYear, v.PersonalMonth, v.PersonalDay)
		}
	}
	for _, v := range f.Vectors {
		asOf, err := time.Parse(time.DateOnly, v.AsOf)
		if err != nil {
			t.Fatal(err)
		}
		check(v, asOf)
	}
	for _, v := range f.TimezoneVectors {
		at, err := time.Parse(time.RFC3339, v.Instant)
		if err != nil {
			t.Fatal(err)
		}
		loc, err := tz.Load(v.TZ)
		if err != nil {
			t.Fatal(err)
		}
		local := at.In(loc)
		if got := local.Format(time.DateOnly); got != v.AsOf {
			t.Errorf("%s in %s is %s, want %s", v.Instant, v.TZ, got, v.AsOf)
		}
		check(v, local)
	}
}

func TestLifePathWorkedExample(t *testing.T) {
	// 29 November 1990: month 11 (master), day 29 → 11, year 1990 → 1;
	// 11 + 11 + 1 = 23 → 5.
	r := LifePathReduction(1990, 11, 29)
	if r.Number != 5 || r.Total != 23 || r.Master {
		t.Fatalf("got %+v", r)
	}
	want := []ReductionStep{
		{Label: "month", Value: 11, Reduced: 11},
		{Label: "day", Value: 29, Reduced: 11, Steps: []string{"2+9=11"}},
		{Label: "year", Value: 1990, Reduced: 1, Steps: []string{"1+9+9+0=19", "1+9=10", "1+0=1"}},
	}
	if !reflect.DeepEqual(r.Components, want) || !reflect.DeepEqual(r.Final, []string{"2+3=5"}) {
		t.Errorf("components %+v final %v", r.Components, r.Final)
	}
	// 1980-01-01 keeps the master 11 that a single digit sum loses.
	if got := LifePath(1980, 1, 1); got != 11 {
		t.Errorf("LifePath(1980-01-01) = %d, want 11", got)
	}
}

func TestPersonalCycles(t *testing.T) {
	asOf := time.Date(2026, 11, 4, 9, 0, 0, 0, time.UTC)
	// Birth 1987-11-29: PY = R(2 + 2 + 1) = 5, PM = R(5 + 11) = 7, PD = R(7 + 4) = 2.
	if py, pm, pd := PersonalYear(11, 29, asOf), PersonalMonth(11, 29, asOf), PersonalDay(11, 29, asOf); py != 5 || pm != 7 || pd != 2 {
		t.Errorf("PY/PM/PD = %d/%d/%d, want 5/7/2", py, pm, pd)
	}
	for m := 1; m <= 12; m++ {
		for d := 1; d <= 31; d += 3 {
			for _, n := range []int{PersonalYear(m, d, asOf), PersonalMonth(m, d, asOf), PersonalDay(m, d, asOf)} {
				if n < 1 || n > 9 {
					t.Fatalf("personal cycle %d out of 1..9 for %d/%d", n, m, d)
				}
			}
		}
	}
	r := PersonalMonthReduction(11, 29, asOf)
	if r.Total != 16 || r.Number != 7 || len(r.Components) != 2 {
		t.Errorf("personal month reduction %+v", r)
	}
	if !IsMasterNumber(33) || IsMasterNumber(44) {
		t.Error("IsMasterNumber")
	}
}
