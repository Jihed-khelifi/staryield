// Command placesmigration writes the data migration that moves birth places
// chosen from the original 173-city list ("paris-fr") to their GeoNames
// places ("gn:2988507"), with GeoNames coordinates, region and zone.
//
//	go run ./scripts/placesmigration -out internal/migrations/sql/0006_places_geonames.sql
//
// The output is committed; once applied, a migration never changes, so the
// command is only rerun before the migration first ships.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"log"
	"os"
	"strconv"
	"strings"

	"github.com/Jihed-khelifi/staryield/backend/internal/astro/geo"
)

const header = `-- 0006_places_geonames: birth places move to the GeoNames gazetteer
-- (cities5000, CC BY 4.0). Generated by scripts/placesmigration.

ALTER TABLE user_profiles
    ADD COLUMN birth_admin1 text NOT NULL DEFAULT ''
        CHECK (char_length(birth_admin1) <= 120),
    ADD COLUMN birth_place_source text NOT NULL DEFAULT ''
        CHECK (birth_place_source IN ('', 'geonames', 'legacy'));

-- Places chosen from the original 173-city list move to the matching
-- GeoNames place: the same city, country and time zone, within 60 km.
UPDATE user_profiles AS p
SET birth_place_id     = m.gn_id,
    birth_place        = m.label,
    birth_admin1       = m.admin1,
    birth_latitude     = m.lat,
    birth_longitude    = m.lon,
    birth_timezone     = m.tz,
    birth_place_source = 'geonames',
    updated_at         = now()
FROM (VALUES
`

const footer = `) AS m (slug, gn_id, label, admin1, lat, lon, tz)
WHERE p.birth_place_id = m.slug;

-- Mark every other stored place: GeoNames IDs as such, anything else as
-- predating the gazetteer (kept as entered).
UPDATE user_profiles
SET birth_place_source = CASE WHEN birth_place_id LIKE 'gn:%' THEN 'geonames' ELSE 'legacy' END
WHERE birth_place_id <> '' AND birth_place_source = '';
`

func quote(s string) string { return "'" + strings.ReplaceAll(s, "'", "''") + "'" }

func number(f float64) string { return strconv.FormatFloat(f, 'f', -1, 64) }

func main() {
	out := flag.String("out", "", "output file (stdout when empty)")
	flag.Parse()

	var b bytes.Buffer
	b.WriteString(header)
	slugs := geo.LegacySlugs()
	for i, slug := range slugs {
		p, ok := geo.ByID(slug)
		if !ok {
			log.Fatalf("legacy place %s has no GeoNames entry", slug)
		}
		label := []rune(p.Label())
		if len(label) > 120 {
			label = label[:120]
		}
		sep := ","
		if i == len(slugs)-1 {
			sep = ""
		}
		fmt.Fprintf(&b, "    (%s, %s, %s, %s, %s, %s, %s)%s\n", quote(slug), quote(p.ID), quote(string(label)), quote(p.Admin1),
			number(p.Latitude), number(p.Longitude), quote(p.TimeZone), sep)
	}
	b.WriteString(footer)

	if *out == "" {
		_, _ = os.Stdout.Write(b.Bytes())
		return
	}
	if err := os.WriteFile(*out, b.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
}
